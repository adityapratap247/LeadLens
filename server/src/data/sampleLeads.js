// Algorithmic generator to reliably expand to 200 high-quality diverse leads
export function generateSampleLeads(count = 200) {
  const industries = [
    { name: "SaaS", weight: 0.3, keywords: ["cloud", "automation", "b2b", "workflow", "subscription"] },
    { name: "Fintech", weight: 0.2, keywords: ["payments", "banking", "treasury", "compliance", "fraud"] },
    { name: "AI/ML", weight: 0.2, keywords: ["llm", "agents", "machine learning", "analytics", "neural"] },
    { name: "Cybersecurity", weight: 0.15, keywords: ["soc2", "zero-trust", "firewall", "encryption", "threat"] },
    { name: "Enterprise Software", weight: 0.15, keywords: ["erp", "crm", "infrastructure", "devops", "enterprise"] }
  ];

  const seniorities = [
    { title: "Chief Technology Officer", level: "C-level" },
    { title: "Chief Executive Officer", level: "C-level" },
    { title: "Founder & CEO", level: "C-level" },
    { title: "Chief Information Security Officer", level: "C-level" },
    { title: "Chief Revenue Officer", level: "C-level" },
    { title: "VP of Engineering", level: "VP" },
    { title: "VP of Product", level: "VP" },
    { title: "VP of Growth", level: "VP" },
    { title: "Director of Technology", level: "Director" },
    { title: "Head of AI & Innovation", level: "Director" },
    { title: "Head of Infrastructure", level: "Director" },
    { title: "Engineering Manager", level: "Manager" },
    { title: "Senior Software Engineer", level: "IC" },
    { title: "Account Executive", level: "IC" }
  ];

  const locations = [
    { city: "San Francisco, CA", region: "North America" },
    { city: "New York, NY", region: "North America" },
    { city: "Austin, TX", region: "North America" },
    { city: "Seattle, WA", region: "North America" },
    { city: "Boston, MA", region: "North America" },
    { city: "Toronto, Canada", region: "North America" },
    { city: "London, UK", region: "Europe" },
    { city: "Berlin, Germany", region: "Europe" },
    { city: "Amsterdam, Netherlands", region: "Europe" },
    { city: "Paris, France", region: "Europe" },
    { city: "Singapore", region: "APAC" },
    { city: "Sydney, Australia", region: "APAC" },
    { city: "Remote, Worldwide", region: "Remote" }
  ];

  const firstNames = ["Marcus", "Sarah", "Elena", "David", "Alexander", "Rachel", "Jonathan", "Klaus", "Emily", "Cian", "Sophie", "Jan", "Maya", "Robert", "Wei", "Liam", "Jessica", "Brandon", "Astrid", "Trevor", "Chloe", "Devon", "Aaliyah", "Zack", "Tara", "Lucas", "Vikram", "Nina", "Oliver", "Camila"];
  const lastNames = ["Jenkins", "Vance", "Rostova", "Chen", "Hayes", "Green", "Lee", "Meier", "Watson", "O'Connor", "Becker", "Berg", "Lin", "Garcia", "Zhang", "Hemsworth", "Taylor", "Cole", "Lind", "Noah", "Dupont", "Sterling", "Kowalski", "Patel", "Nakamura", "Alvarez", "Larsson", "Dubois"];

  const prefixes = ["Hyper", "Omni", "Meta", "Aero", "Pulse", "Stratum", "Cyber", "Synapse", "Quantum", "Apex", "Vortex", "Crest", "Nova", "Stratos", "Beacon", "Lumina", "Forge", "Optima", "Kore", "Verve", "Prism", "Echo", "Atlas", "Vector", "Zeta", "Flux"];
  const suffixes = ["Flow", "Scale", "Stack", "Sync", "Mesh", "Logic", "Guard", "Metrics", "Wave", "Point", "Base", "Nest", "Labs", "Engine", "Works", "Hub", "Matrix", "Bridge", "Dynamics", "Link"];
  const tlds = ["io", "com", "ai", "co", "tech", "net", "cloud", "dev"];

  const leads = [...RAW_SAMPLE_LEADS];
  let seed = 42;
  const pseudoRand = () => {
    seed = (seed * 9301 + 49297) % 233280;
    return seed / 233280;
  };

  while (leads.length < count) {
    const idx = leads.length;
    const prefix = prefixes[Math.floor(pseudoRand() * prefixes.length)];
    const suffix = suffixes[Math.floor(pseudoRand() * suffixes.length)];
    const company = `${prefix}${suffix} ${idx % 3 === 0 ? 'AI' : idx % 5 === 0 ? 'Cloud' : 'Systems'}`;
    const tld = tlds[Math.floor(pseudoRand() * tlds.length)];
    const domain = `${prefix.toLowerCase()}${suffix.toLowerCase()}${idx > 50 ? idx : ''}.${tld}`;

    const industryObj = industries[Math.floor(pseudoRand() * industries.length)];
    const seniorityObj = seniorities[Math.floor(pseudoRand() * seniorities.length)];
    const locObj = locations[Math.floor(pseudoRand() * locations.length)];
    const firstName = firstNames[Math.floor(pseudoRand() * firstNames.length)];
    const lastName = lastNames[Math.floor(pseudoRand() * lastNames.length)];
    const contactName = `${firstName} ${lastName}`;

    const emailPrefix = pseudoRand() > 0.5 ? `${firstName.toLowerCase()}.${lastName.toLowerCase()}` : firstName.toLowerCase();
    const email = `${emailPrefix}@${domain}`;
    
    // Vary employee sizes realistically: 15 to 2500
    const employeeCount = Math.floor(pseudoRand() * pseudoRand() * 1200) + 18;
    const kw = industryObj.keywords[Math.floor(pseudoRand() * industryObj.keywords.length)];
    const description = `Scalable ${industryObj.name.toLowerCase()} platform providing enterprise ${kw} automation and unified operational telemetry.`;
    const emailVerified = pseudoRand() > 0.15; // 85% verified

    leads.push({
      company,
      domain,
      industry: industryObj.name,
      employeeCount,
      location: locObj.city,
      region: locObj.region,
      contactName,
      title: seniorityObj.title,
      email,
      description,
      emailVerified,
      source: 'sample'
    });
  }

  return leads.slice(0, count);
}

